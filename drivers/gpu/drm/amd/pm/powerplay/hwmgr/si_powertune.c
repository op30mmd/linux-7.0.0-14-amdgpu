static void si_update_dte_from_pl2(struct pp_hwmgr *hwmgr,
				   struct si_dte_data *dte_data)
{
	uint32_t p_limit1 = hwmgr->platform_descriptor.TDPLimit;
	uint32_t p_limit2 = hwmgr->platform_descriptor.nearTDPLimit;
	uint32_t k = dte_data->k;
	uint32_t t_max = dte_data->max_t;
	uint32_t t_split[5] = { 10, 15, 20, 25, 30 };
	uint32_t t_0 = dte_data->t0;
	uint32_t i;

	if (p_limit2 != 0 && p_limit2 <= p_limit1) {
		dte_data->tdep_count = 3;

		for (i = 0; i < k; i++) {
			dte_data->r[i] =
				(t_split[i] * (t_max - t_0 / (uint32_t)1000) * (1 << 14)) /
				(p_limit2 * (uint32_t)100);
		}

		dte_data->tdep_r[1] = dte_data->r[4] * 2;

		for (i = 2; i < SMC_SISLANDS_DTE_MAX_TEMPERATURE_DEPENDENT_ARRAY_SIZE; i++) {
			dte_data->tdep_r[i] = dte_data->r[4];
		}
	} else {
		pr_err("Invalid PL2! DTE will not be updated.\n");
	}
}

